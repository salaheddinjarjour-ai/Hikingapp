export function getTrailById(id: string): SampleTrail | undefined {
  return sampleTrails.find(trail => trail.id === id);
}

export function getTrailsNearCoordinates(lat: number, lng: number, radiusKm: number = 50): SampleTrail[] {
  return sampleTrails.filter(trail => {
    const trailLat = trail.location.coordinates[1];
    const trailLng = trail.location.coordinates[0];
    const distance = Math.sqrt(
      Math.pow((trailLat - lat) * 111, 2) + 
      Math.pow((trailLng - lng) * 85, 2)
    );
    return distance <= radiusKm;
  });
}
